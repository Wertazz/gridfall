type C2D = CanvasRenderingContext2D | OffscreenCanvasRenderingContext2D;

export function pixelText(c: C2D, text: string, x: number, y: number, color: string, scale = 1) {
  c.fillStyle = color;
  let cx = x;
  for (const ch of text.toUpperCase()) {
    const g = G[ch] ?? G['?'];
    for (let k = 0; k < 15; k++) if (g[k] === '1') c.fillRect(cx + (k % 3) * scale, y + ((k / 3) | 0) * scale, scale, scale);
    cx += 4 * scale;
  }
  return cx - x;
}
export const textWidth = (t: string, scale = 1) => t.length * 4 * scale - scale;
